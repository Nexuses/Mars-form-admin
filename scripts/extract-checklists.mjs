/**
 * Regenerates the checklist catalog and the bundled MARS checklist pages from
 * the reference form export.
 *
 *   node scripts/extract-checklists.mjs "MARS_Candidate_Application_Form.html"
 */
import fs from "node:fs";
import path from "node:path";

const source = process.argv[2] || "MARS_Candidate_Application_Form.html";
const html = fs.readFileSync(source, "utf8");

/* ---------- embedded checklist pages -> public/checklists ---------- */

const tag = '<script id="checklist-data" type="application/json">';
const start = html.indexOf(tag);
const open = html.indexOf(">", start) + 1;
const pages = JSON.parse(html.slice(open, html.indexOf("</script>", open)));

const outDir = path.join("public", "checklists");
fs.mkdirSync(outDir, { recursive: true });
for (const [name, body] of Object.entries(pages)) {
  fs.writeFileSync(path.join(outDir, name), body, "utf8");
}

/* ---------- checklist catalog -> src/lib/application/checklists.ts ---------- */

const listStart = html.indexOf("checklists: [");
const listEnd = html.indexOf("\n    ],", listStart);
const rows = html
  .slice(listStart, listEnd)
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line.startsWith("{ group:"));

/** Reads key: 'value' pairs, honouring \' escapes. */
function field(row, key) {
  const re = new RegExp(`${key}: '((?:[^'\\\\]|\\\\.)*)'`);
  const m = re.exec(row);
  return m ? m[1].replace(/\\'/g, "'").replace(/\\\\/g, "\\") : null;
}

const items = rows.map((row) => ({
  group: field(row, "group"),
  label: field(row, "label"),
  url: field(row, "url"),
  page: field(row, "page"),
}));

const missing = items.filter((i) => !i.group || !i.label || (!i.url && !i.page));
if (missing.length) {
  throw new Error(`Unparsed checklist rows: ${JSON.stringify(missing)}`);
}

const q = (s) => JSON.stringify(s);
const body = items
  .map((i) => {
    const target = i.page ? `page: ${q(i.page)}` : `url: ${q(i.url)}`;
    return `  { group: ${q(i.group)}, label: ${q(i.label)}, ${target} },`;
  })
  .join("\n");

const file = `// Generated by scripts/extract-checklists.mjs — do not edit by hand.
import type { ChecklistItem } from "./config";

export const CHECKLISTS: ChecklistItem[] = [
${body}
];
`;

fs.writeFileSync(path.join("src", "lib", "application", "checklists.ts"), file, "utf8");

console.log(
  `Wrote ${Object.keys(pages).length} checklist pages to ${outDir} and ${items.length} catalog entries.`,
);
